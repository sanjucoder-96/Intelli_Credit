"""Async Alembic environment for the IntelliCredit backend.

Target metadata is ``app.infrastructure.db.base.Base.metadata`` with the full
models package imported first so every table is registered. The database URL
comes from application Settings (``IC_DATABASE__URL``) unless overridden via
the ``ALEMBIC_DATABASE_URL`` environment variable (CI and one-off runs).
Phase 3+ migrations are autogenerated against this same env; 0001 is
hand-written.
"""

from __future__ import annotations

import asyncio
import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import create_async_engine

import app.infrastructure.db.models  # noqa: F401  (populates Base.metadata)
from app.infrastructure.db.base import Base

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def _database_url() -> str:
    """Resolve the migration URL: env override first, then app Settings."""
    override = os.environ.get("ALEMBIC_DATABASE_URL")
    if override:
        return override
    from app.core.config import get_settings

    return get_settings().database.url


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode: emit SQL to stdout, no DBAPI."""
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        compare_type=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def _run_async_migrations() -> None:
    """Create an async engine and run migrations through a sync bridge."""
    engine = create_async_engine(_database_url(), poolclass=pool.NullPool)
    async with engine.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await engine.dispose()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode against a live database."""
    asyncio.run(_run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
